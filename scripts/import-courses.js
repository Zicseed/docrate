// Turns data/docrate_courses.csv into supabase/import_courses.sql (paste that into Supabase -> SQL Editor).
// Re-runnable: each course has a stable code, so running the SQL again updates courses instead of duplicating them.
// Usage: node scripts/import-courses.js
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, "..");
const UNIS = { CIU: "ciu", NVU: "newvision", SEU: "seu", TSMU: "tsmu" };
const FACULTY = { MD: "Medicine (MD)", DMD: "Dentistry" };

// Minimal CSV parser (handles quoted fields with commas and "" escapes).
function parseCSV(text) {
  const rows = []; let row = [], field = "", q = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (q) { if (ch === '"' && text[i + 1] === '"') { field += '"'; i++; } else if (ch === '"') q = false; else field += ch; }
    else if (ch === '"') q = true;
    else if (ch === ",") { row.push(field); field = ""; }
    else if (ch === "\n" || ch === "\r") { if (ch === "\r" && text[i + 1] === "\n") i++; row.push(field); rows.push(row); row = []; field = ""; }
    else field += ch;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows.filter(r => r.some(x => x.trim()));
}

const [head, ...lines] = parseCSV(fs.readFileSync(path.join(root, "data/docrate_courses.csv"), "utf8"));
const rows = lines.map((l, i) => Object.assign({ line: i + 2 }, Object.fromEntries(head.map((h, j) => [h.trim(), (l[j] || "").trim()]))));
const failed = [], ok = [];
rows.forEach(r => {
  if (!UNIS[r.university]) return failed.push(r.line + ": unknown university " + r.university);
  if (!FACULTY[r.program]) return failed.push(r.line + ": unknown program " + r.program);
  if (!r.course_name) return failed.push(r.line + ": no course name");
  if (r.semester && !/^([1-9]|1[0-2])$/.test(r.semester)) return failed.push(r.line + ": bad semester " + r.semester);
  ok.push(r);
});

// A name repeated in several semesters of the same program gets the semester number added ("Human Anatomy 2").
const key = r => r.university + "|" + r.program + "|" + r.course_name;
const repeats = {}; ok.forEach(r => { repeats[key(r)] = (repeats[key(r)] || 0) + 1; });
const slug = s => s.toUpperCase().replace(/[^A-Z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 60);
const courses = ok.map(r => {
  const name = repeats[key(r)] > 1 && r.semester ? r.course_name + " " + r.semester : r.course_name;
  const sem = r.semester ? "S" + r.semester.padStart(2, "0") : "NS";
  const code = r.code ? r.university + "-" + r.program + "-" + r.code.replace(/\s+/g, "")
    : r.university + "-" + r.program + "-" + sem + "-" + slug(name);
  const c = { code, name, uniId: UNIS[r.university], faculty: FACULTY[r.program], credits: r.ects ? r.ects + " ECTS" : "",
    status: r.status, notes: [r.semester_note, r.notes].filter(Boolean).join(" · "), rating: 0, difficulty: 0, workload: "Moderate", exam: "Moderate", line: r.line };
  if (r.semester) c.semester = "Semester " + r.semester;
  return c;
});
const seen = {};
const unique = courses.filter(c => { if (seen[c.code]) { failed.push(c.line + ": duplicate code " + c.code + " (same as line " + seen[c.code] + ")"); return false; } seen[c.code] = c.line; return true; });
unique.forEach(c => delete c.line);

const counts = {}; unique.forEach(c => { const k = Object.keys(UNIS).find(u => UNIS[u] === c.uniId) + " " + (c.faculty === "Dentistry" ? "DMD" : "MD"); counts[k] = (counts[k] || 0) + 1; });
const json = JSON.stringify(unique, null, 1);
if (json.includes("$json$")) throw new Error("CSV contains $json$");

const sql = `-- DocRate: courses for CIU, NVU, SEU and TSMU. GENERATED by scripts/import-courses.js from data/docrate_courses.csv.
-- Run in Supabase Dashboard -> SQL Editor. Safe to re-run: existing codes are updated, new ones added, nothing duplicated.
-- Also adds Caucasus International University (CIU) and makes all four universities live.

do $$
declare
  v_admin uuid; v_type text; v_utype text; v_cols text; v_set text; v_code_expr text; v_data_col text;
  v_added int := 0; v_updated int := 0; c jsonb; v_codes text[];
begin
  select id into v_admin from public.profiles where role = 'admin' order by id limit 1;
  if v_admin is null then raise exception 'No admin account found in profiles.'; end if;
  perform set_config('request.jwt.claims', json_build_object('sub', v_admin, 'role', 'authenticated')::text, true);
  perform set_config('request.jwt.claim.sub', v_admin::text, true);
  select format_type(p.proargtypes[0], null) into v_type from pg_proc p where p.proname = 'admin_add_course' and p.pronamespace = 'public'::regnamespace limit 1;
  select format_type(p.proargtypes[0], null) into v_utype from pg_proc p where p.proname = 'admin_add_university' and p.pronamespace = 'public'::regnamespace limit 1;
  if v_type is null or v_utype is null then raise exception 'admin_add_course() / admin_add_university() not found.'; end if;

  -- CIU (the other three already exist)
  if not exists (select 1 from jsonb_array_elements((public.catalogue_public())::jsonb -> 'unis') u where u ->> 'id' = 'ciu') then
    execute format('select public.admin_add_university($1::%s)', v_utype) using
      '{"id":"ciu","short":"CIU","name":"Caucasus International University","city":"Tbilisi","founded":"","website":"","overall":0,"reviewCount":0,"professorCount":0,"faculties":["Medicine (MD)","Dentistry"],"r":[0,0,0,0,0]}'::jsonb;
  end if;
  insert into public.university_visibility (uni_id, hidden, updated_at)
  select x, false, now() from unnest(array['ciu','newvision','seu','tsmu']) x
  on conflict (uni_id) do update set hidden = false, updated_at = now();

  -- How catalogue_courses stores a course: plain columns, a json column, or both.
  select data_type_col into v_data_col from (select column_name as data_type_col from information_schema.columns
    where table_schema = 'public' and table_name = 'catalogue_courses' and data_type in ('jsonb','json') order by (column_name = 'data') desc limit 1) s;
  v_code_expr := case when exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'catalogue_courses' and column_name = 'code')
    then 'code' else format('(%I ->> %L)', v_data_col, 'code') end;
  select string_agg(format('%I = coalesce($1 ->> %L, %I)', column_name, column_name, column_name), ', ') into v_cols
    from information_schema.columns where table_schema = 'public' and table_name = 'catalogue_courses'
    and column_name in ('name','uni_id','faculty','semester','credits') and data_type in ('text','character varying');
  v_set := concat_ws(', ', v_cols, case when v_data_col is not null then format('%I = %I || $1', v_data_col, v_data_col) end);
  if v_set = '' then raise exception 'Unexpected catalogue_courses layout: %', (select string_agg(column_name || ' ' || data_type, ', ') from information_schema.columns where table_schema = 'public' and table_name = 'catalogue_courses'); end if;

  v_codes := array(select x ->> 'code' from jsonb_array_elements((public.catalogue_public())::jsonb -> 'courses') x);
  for c in select value from jsonb_array_elements($json$${json}$json$::jsonb) loop
    if (c ->> 'code') = any(v_codes) then
      execute format('update public.catalogue_courses set %s where %s = $2', v_set, v_code_expr) using c, c ->> 'code';
      v_updated := v_updated + 1;
    else
      execute format('select public.admin_add_course($1::%s)', v_type) using c;
      v_added := v_added + 1;
    end if;
  end loop;
  raise notice 'Courses: % added, % updated.', v_added, v_updated;
end;
$$;

-- Check: course counts per university and program (expected ${Object.entries(counts).map(([k, v]) => k + " " + v).join(", ")}).
select x ->> 'uniId' as university, x ->> 'faculty' as program, count(*) as courses
from jsonb_array_elements((public.catalogue_public())::jsonb -> 'courses') x
where x ->> 'uniId' in ('ciu','newvision','seu','tsmu') group by 1, 2 order by 1, 2;
`;
fs.writeFileSync(path.join(root, "supabase/import_courses.sql"), sql);
console.log("rows read:", rows.length, "| courses written:", unique.length);
console.log("per university/program:", counts);
console.log("renamed (repeated in several semesters):", courses.filter(c => c.name !== (rows.find(r => r.course_name === c.name) || {}).course_name && /\s\d+$/.test(c.name)).length);
console.log(failed.length ? "FAILED ROWS:\n" + failed.join("\n") : "failed rows: none");
